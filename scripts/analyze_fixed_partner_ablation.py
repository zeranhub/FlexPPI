def json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(item) for item in value]
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        return None if not np.isfinite(value) else float(value)
    if pd.isna(value) if not isinstance(value, str) else False:
        return None
    return value


def dump_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(json_safe(value), indent=2, ensure_ascii=False, allow_nan=False),
        encoding="utf-8",
    )


def bh_adjust(pvalues: Sequence[float]) -> np.ndarray:
    values = np.asarray(pvalues, dtype=float)
    output = np.full(len(values), np.nan, dtype=float)
    valid = np.flatnonzero(np.isfinite(values))
    if not len(valid):
        return output
    order = valid[np.argsort(values[valid])]
    ranked = values[order] * len(order) / np.arange(1, len(order) + 1)
    ranked = np.minimum.accumulate(ranked[::-1])[::-1]
    output[order] = np.minimum(ranked, 1.0)
    return output


def safe_wilcoxon(values: Iterable[float]) -> Optional[float]:
    array = np.asarray(list(values), dtype=float)
    array = array[np.isfinite(array) & (np.abs(array) > 1e-12)]
    if not len(array):
        return None
    try:
        return float(wilcoxon(array, alternative="two-sided").pvalue)
    except ValueError:
        return None


def prepare_frame(path: Path, contact_cutoff: float) -> pd.DataFrame:
    columns = [
        "pdb_id",
        "chain",
        "chain_role",
        "author_residue_id",
        "reference_condition",
        "external_clean",
        "chi_defined",
        "target_chainfit_rmsf_angstrom",
        "full_rmsf",
        "reference_rmsf",
        "binding_context_delta_rmsf",
        "binding_context_delta_chi_entropy",
        "binding_context_delta_sasa",
        "min_distance_to_tcr_angstrom",
        "min_distance_to_peptide_angstrom",
        "min_distance_to_mhc_angstrom",
    ]
    frame = pd.read_csv(path, usecols=columns, low_memory=False)
    for column in ("external_clean", "chi_defined"):
        if frame[column].dtype != bool:
            frame[column] = frame[column].astype(str).str.lower().eq("true")
    frame = frame[frame["external_clean"]].copy()
    frame["side"] = np.where(frame["chain_role"].isin(PMHC_ROLES), "pMHC", "TCR")
    if not frame.loc[frame["side"].eq("pMHC"), "reference_condition"].eq("pmhc").all():
        raise ValueError("pMHC residues are not matched to the pMHC-only input")
    if not frame.loc[frame["side"].eq("TCR"), "reference_condition"].eq("tcr").all():
        raise ValueError("TCR residues are not matched to the TCR-only input")
    tcr_distance = frame[["min_distance_to_mhc_angstrom", "min_distance_to_peptide_angstrom"]].min(
        axis=1, skipna=True
    )
    frame["partner_distance_angstrom"] = np.where(
        frame["side"].eq("pMHC"), frame["min_distance_to_tcr_angstrom"], tcr_distance
    )
    frame["direct_partner_contact"] = frame["partner_distance_angstrom"] <= contact_cutoff
    frame["distance_bin"] = pd.Categorical(
        np.select(
            [
                frame["partner_distance_angstrom"] <= 5.0,
                frame["partner_distance_angstrom"] <= 8.0,
                frame["partner_distance_angstrom"] <= 12.0,
            ],
            ["0--5", "5--8", "8--12"],
            default=">12",
        ),
        categories=[label for label, _, _ in DISTANCE_BINS],
        ordered=True,
    )
    return frame


def compute_chain_metrics(frame: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
    rows: List[Dict[str, Any]] = []
    for (pdb_id, chain), group in frame.groupby(["pdb_id", "chain"], sort=True):
        target = group["target_chainfit_rmsf_angstrom"].to_numpy(dtype=float)
        full = _system_metrics(group["full_rmsf"].to_numpy(dtype=float), target, True)
        removed = _system_metrics(group["reference_rmsf"].to_numpy(dtype=float), target, True)
        row: Dict[str, Any] = {
            "pdb_id": pdb_id,
            "chain": chain,
            "chain_role": str(group["chain_role"].iloc[0]),
            "side": str(group["side"].iloc[0]),
            "residue_count": int(len(group)),
        }
        for metric in STATE_METRICS:
            row[f"full_{metric}"] = full.get(metric)
            row[f"partner_removed_{metric}"] = removed.get(metric)
            if full.get(metric) is not None and removed.get(metric) is not None:
                row[f"full_advantage_{metric}"] = ADVANTAGE_DIRECTION[metric] * (
                    float(full[metric]) - float(removed[metric])
                )
        rows.append(row)
    chain = pd.DataFrame(rows)
    metric_columns = [
        column
        for column in chain.columns
        if column.startswith(("full_", "partner_removed_"))
    ]
    complex_frame = (
        chain.groupby("pdb_id", sort=True)[metric_columns]
        .mean(numeric_only=True)
        .reset_index()
        .merge(
            chain.groupby("pdb_id", sort=True)
            .agg(chain_count=("chain", "nunique"), residue_count=("residue_count", "sum"))
            .reset_index(),
            on="pdb_id",
            how="left",
            validate="one_to_one",
        )
    )
    return chain, complex_frame


def summarize_state_metrics(
    complex_frame: pd.DataFrame, repetitions: int, seed: int
) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for index, metric in enumerate(STATE_METRICS):
        pair = complex_frame[[f"full_{metric}", f"partner_removed_{metric}"]].dropna()
        full = pair.iloc[:, 0].to_numpy(dtype=float)
        removed = pair.iloc[:, 1].to_numpy(dtype=float)
        advantage = ADVANTAGE_DIRECTION[metric] * (full - removed)
        ci = _bootstrap_mean_ci(advantage.tolist(), repetitions, seed + index)
        rows.append(
            {
                "metric": metric,
                "complex_count": int(len(pair)),
                "full_macro_mean": float(np.mean(full)),
                "partner_removed_macro_mean": float(np.mean(removed)),
                "mean_full_advantage": float(np.mean(advantage)),
                "median_full_advantage": float(np.median(advantage)),
                "bootstrap_ci_low": ci[0] if ci else math.nan,
                "bootstrap_ci_high": ci[1] if ci else math.nan,
                "full_win_rate": float(np.mean(advantage > 1e-12)),
                "wilcoxon_two_sided_p": safe_wilcoxon(advantage),
            }
        )
    output = pd.DataFrame(rows)
    output["benjamini_hochberg_q"] = bh_adjust(output["wilcoxon_two_sided_p"])
    return output


def metric_subset(frame: pd.DataFrame, metric: str) -> pd.DataFrame:
    selected = frame
    if metric == "chi_entropy":
        selected = selected[selected["chi_defined"]]
    column = f"binding_context_delta_{metric}"
    return selected[np.isfinite(selected[column]) & np.isfinite(selected["partner_distance_angstrom"])].copy()


def interface_localization(
    frame: pd.DataFrame, repetitions: int, seed: int
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    per_side_rows: List[Dict[str, Any]] = []
    for metric in RESPONSE_METRICS:
        selected = metric_subset(frame, metric)
        column = f"binding_context_delta_{metric}"
        for (pdb_id, side), group in selected.groupby(["pdb_id", "side"], sort=True):
            contact = group.loc[group["direct_partner_contact"], column]
            noncontact = group.loc[~group["direct_partner_contact"], column]
            if contact.empty or noncontact.empty:
                continue
            per_side_rows.append(
                {
                    "pdb_id": pdb_id,
                    "side": side,
                    "metric": metric,
                    "contact_residue_count": int(len(contact)),
                    "noncontact_residue_count": int(len(noncontact)),
                    "contact_mean_delta": float(contact.mean()),
                    "noncontact_mean_delta": float(noncontact.mean()),
                    "contact_minus_noncontact_delta": float(contact.mean() - noncontact.mean()),
                }
            )
    per_side = pd.DataFrame(per_side_rows)
    per_complex = (
        per_side.groupby(["pdb_id", "metric"], sort=True)[
            ["contact_mean_delta", "noncontact_mean_delta", "contact_minus_noncontact_delta"]
        ]
        .mean()
        .reset_index()
    )
    rows: List[Dict[str, Any]] = []
    side_rows: List[Dict[str, Any]] = []
    for metric_index, metric in enumerate(RESPONSE_METRICS):
        group = per_complex[per_complex["metric"].eq(metric)]
        effect = group["contact_minus_noncontact_delta"].to_numpy(dtype=float)
        ci = _bootstrap_mean_ci(effect.tolist(), repetitions, seed + metric_index)
        rows.append(
            {
                "metric": metric,
                "complex_count": int(len(group)),
                "contact_macro_mean_delta": float(group["contact_mean_delta"].mean()),
                "noncontact_macro_mean_delta": float(group["noncontact_mean_delta"].mean()),
                "mean_contact_minus_noncontact_delta": float(np.mean(effect)),
                "bootstrap_ci_low": ci[0] if ci else math.nan,
                "bootstrap_ci_high": ci[1] if ci else math.nan,
                "fraction_complexes_stronger_negative_at_contact": float(np.mean(effect < 0)),
                "wilcoxon_two_sided_p": safe_wilcoxon(effect),
            }
        )
        for side_index, side in enumerate(("pMHC", "TCR")):
            side_group = per_side[
                per_side["metric"].eq(metric) & per_side["side"].eq(side)
            ]
            side_effect = side_group["contact_minus_noncontact_delta"].to_numpy(dtype=float)
            side_ci = _bootstrap_mean_ci(
                side_effect.tolist(), repetitions, seed + 20 + metric_index * 2 + side_index
            )
            side_rows.append(
                {
                    "metric": metric,
                    "side": side,
                    "complex_count": int(len(side_group)),
                    "contact_macro_mean_delta": float(side_group["contact_mean_delta"].mean()),
                    "noncontact_macro_mean_delta": float(side_group["noncontact_mean_delta"].mean()),
                    "mean_contact_minus_noncontact_delta": float(np.mean(side_effect)),
                    "bootstrap_ci_low": side_ci[0] if side_ci else math.nan,
                    "bootstrap_ci_high": side_ci[1] if side_ci else math.nan,
                }
            )
    summary = pd.DataFrame(rows)
    summary["benjamini_hochberg_q"] = bh_adjust(summary["wilcoxon_two_sided_p"])
    return per_side, summary, pd.DataFrame(side_rows)


def distance_response(
    frame: pd.DataFrame, repetitions: int, seed: int
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    rows: List[Dict[str, Any]] = []
    for metric in RESPONSE_METRICS:
        selected = metric_subset(frame, metric)
        column = f"binding_context_delta_{metric}"
        for (pdb_id, side), group in selected.groupby(["pdb_id", "side"], sort=True):
            pair = group[["partner_distance_angstrom", column]].dropna()
            if len(pair) < 4 or pair.iloc[:, 0].nunique() < 2 or pair.iloc[:, 1].nunique() < 2:
                continue
            rho = float(spearmanr(pair.iloc[:, 0], pair.iloc[:, 1]).statistic)
            if np.isfinite(rho):
                rows.append(
                    {
                        "pdb_id": pdb_id,
                        "side": side,
                        "metric": metric,
                        "residue_count": int(len(pair)),
                        "spearman_rho": rho,
                    }
                )
    per_side = pd.DataFrame(rows)
    per_complex = (
        per_side.groupby(["pdb_id", "metric"], sort=True)["spearman_rho"]
        .mean()
        .reset_index()
    )
    summary_rows: List[Dict[str, Any]] = []
    for index, metric in enumerate(RESPONSE_METRICS):
        values = per_complex.loc[per_complex["metric"].eq(metric), "spearman_rho"].to_numpy(dtype=float)
        ci = _bootstrap_mean_ci(values.tolist(), repetitions, seed + index)
        summary_rows.append(
            {
                "metric": metric,
                "complex_count": int(len(values)),
                "mean_within_complex_side_averaged_spearman": float(np.mean(values)),
                "median_within_complex_side_averaged_spearman": float(np.median(values)),
                "bootstrap_ci_low": ci[0] if ci else math.nan,
                "bootstrap_ci_high": ci[1] if ci else math.nan,
                "fraction_positive": float(np.mean(values > 0)),
                "wilcoxon_two_sided_p": safe_wilcoxon(values),
            }
        )
    summary = pd.DataFrame(summary_rows)
    summary["benjamini_hochberg_q"] = bh_adjust(summary["wilcoxon_two_sided_p"])
    return per_side, summary


def distance_bin_summary(
    frame: pd.DataFrame, repetitions: int, seed: int
) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    order = [label for label, _, _ in DISTANCE_BINS]
    for metric_index, metric in enumerate(RESPONSE_METRICS):
        selected = metric_subset(frame, metric)
        column = f"binding_context_delta_{metric}"
        per_side = (
            selected.groupby(["pdb_id", "side", "distance_bin"], observed=True)[column]
            .mean()
            .reset_index(name="mean_delta")
        )
        per_complex = (
            per_side.groupby(["pdb_id", "distance_bin"], observed=True)["mean_delta"]
            .mean()
            .reset_index()
        )
        for bin_index, label in enumerate(order):
            values = per_complex.loc[
                per_complex["distance_bin"].astype(str).eq(label), "mean_delta"
            ].to_numpy(dtype=float)
            ci = _bootstrap_mean_ci(
                values.tolist(), repetitions, seed + metric_index * 10 + bin_index
            )
            rows.append(
                {
                    "metric": metric,
                    "distance_bin_angstrom": label,
                    "complex_count": int(len(values)),
                    "macro_mean_delta": float(np.mean(values)),
                    "bootstrap_ci_low": ci[0] if ci else math.nan,
                    "bootstrap_ci_high": ci[1] if ci else math.nan,
                }
            )
    return pd.DataFrame(rows)


def atom_coordinate_map(path: Path) -> Dict[Tuple[str, str, str, str, str, str], np.ndarray]:
    result: Dict[Tuple[str, str, str, str, str, str], np.ndarray] = {}
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if not line.startswith("ATOM  ") or len(line) < 54:
                continue
            key = (
                line[21:22],
                line[22:26],
                line[26:27],
                line[17:20],
                line[12:16],
                line[16:17],
            )
            coordinate = np.asarray(
                [float(line[30:38]), float(line[38:46]), float(line[46:54])], dtype=float
            )
            if key in result:
                raise ValueError(f"Duplicate atom identity {key!r} in {path}")
            result[key] = coordinate
    return result


def verify_coordinates(
    manifest_path: Path, prepared_dir: Path, pdb_ids: Sequence[str]
) -> pd.DataFrame:
    manifest = pd.read_csv(manifest_path)
    manifest["pdb_id"] = manifest["pdb_id"].astype(str).str.lower()
    manifest = manifest[manifest["pdb_id"].isin(set(pdb_ids))]
    rows: List[Dict[str, Any]] = []
    for record in manifest.to_dict(orient="records"):
        pdb_id = str(record["pdb_id"])
        full_path = Path(str(record["topology_path"]))
        full = atom_coordinate_map(full_path)
        for condition in ("pmhc", "tcr"):
            subset_path = prepared_dir / pdb_id / f"{pdb_id}_{condition}.pdb"
            subset = atom_coordinate_map(subset_path)
            missing = sorted(set(subset) - set(full))
            differences = [np.max(np.abs(subset[key] - full[key])) for key in subset if key in full]
            rows.append(
                {
                    "pdb_id": pdb_id,
                    "condition": condition,
                    "full_topology": str(full_path.resolve()),
                    "subset_topology": str(subset_path.resolve()),
                    "retained_atom_count": int(len(subset)),
                    "missing_atom_identity_count": int(len(missing)),
                    "maximum_absolute_coordinate_difference_angstrom": (
                        float(np.max(differences)) if differences else math.nan
                    ),
                }
            )
    return pd.DataFrame(rows)


def sci_tex(value: float) -> str:
    if not np.isfinite(value):
        return "--"
    if value == 0:
        return "$0$"
    if 1e-3 <= abs(value) < 1e3:
        return f"${value:.3f}$"
    exponent = int(math.floor(math.log10(abs(value))))
    coefficient = value / (10**exponent)
    return f"${coefficient:.2f}\\times10^{{{exponent}}}$"


