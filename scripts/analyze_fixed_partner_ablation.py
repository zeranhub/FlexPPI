"""Analyze fixed-coordinate partner-context ablation on the ITrace cohort.

The retained pMHC or TCR atoms are identical to their coordinates in the
bound five-chain complex.  The experiment therefore measures model context
sensitivity, not an apo-to-holo physical transition.

This script reuses the frozen-checkpoint predictions generated by
``analyze_itrace_residue_biology.py``.  It does not run or update a model.
"""

